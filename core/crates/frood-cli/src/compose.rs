//! Renders the Docker Compose project for the `compose` deploy target.

use std::net::SocketAddr;
use std::path::Path;

use frood_config::{Loaded, ServerPlacement};

/// PostgreSQL image of the default storage module.
/// PostgreSQL 18 with pgvector (embeddings for search), on the same Debian (and glibc, so
/// the same collations) as the official `postgres:18` image.
pub const POSTGRES_IMAGE: &str = "pgvector/pgvector:pg18-trixie";

/// The HTTPS front (E2): takes a certificate for `server.public_url` and proxies to the server.
pub const CADDY_IMAGE: &str = "caddy:2.10";

pub fn project_name(loaded: &Loaded) -> String {
    format!("frood-{}", loaded.config.installation.name)
}

/// Port the server listens on inside its container (from `server.listen`).
pub fn listen_port(loaded: &Loaded) -> u16 {
    loaded
        .config
        .server
        .listen
        .parse::<SocketAddr>()
        .map_or(8080, |addr| addr.port())
}

/// `config_path` and `secrets_path` must be absolute: Compose resolves paths against the
/// compose file, which lives elsewhere.
pub fn render(
    loaded: &Loaded,
    config_path: &Path,
    secrets_path: &Path,
    deploy_dir: &Path,
) -> String {
    let deploy = &loaded.config.deploy;
    let secrets = quote(&secrets_path.display().to_string());
    let mut out = format!(
        "# Generated by `frood apply` from {config}. Do not edit: changes are overwritten.\n\
         name: {project}\n\
         services:\n\
         \x20 postgres:\n\
         \x20   image: {postgres_image}\n\
         \x20   restart: unless-stopped\n\
         \x20   environment:\n\
         \x20     POSTGRES_USER: frood\n\
         \x20     POSTGRES_DB: frood\n\
         \x20   env_file:\n\
         \x20     - {secrets}\n\
         \x20   ports:\n\
         \x20     - \"127.0.0.1:{pg_port}:5432\"\n\
         \x20   volumes:\n\
         \x20     - pgdata:/var/lib/postgresql\n\
         \x20   healthcheck:\n\
         \x20     test: [\"CMD-SHELL\", \"pg_isready -U frood -d frood\"]\n\
         \x20     interval: 2s\n\
         \x20     timeout: 3s\n\
         \x20     retries: 30\n",
        config = config_path.display(),
        project = project_name(loaded),
        postgres_image = POSTGRES_IMAGE,
        pg_port = deploy.postgres_port,
    );

    if deploy.server == ServerPlacement::Container {
        let port = listen_port(loaded);
        let source = match (&deploy.build, &deploy.image) {
            (Some(build), _) => {
                let path = loaded.base_dir.join(build);
                let path = host_path(&path);
                format!("    build: {}\n", quote(&path.display().to_string()))
            }
            (None, Some(image)) => format!("    image: {}\n", quote(image)),
            (None, None) => unreachable!("validated: container mode has image or build"),
        };
        out.push_str(&format!(
            "  frood:\n\
             {source}\
             \x20   restart: unless-stopped\n\
             \x20   command: [\"serve\", \"--config\", \"/etc/frood/frood.yaml\"]\n\
             \x20   environment:\n\
             \x20     FROOD_DB_HOST: postgres\n\
             \x20     FROOD_DB_PORT: \"5432\"\n\
             \x20   env_file:\n\
             \x20     - {secrets}\n\
             \x20   volumes:\n\
             \x20     - {config_mount}\n\
             \x20   ports:\n\
             \x20     - \"127.0.0.1:{port}:{port}\"\n\
             \x20   depends_on:\n\
             \x20     postgres:\n\
             \x20       condition: service_healthy\n\
             \x20   healthcheck:\n\
             \x20     test: [\"CMD\", \"frood\", \"probe\", \"http://127.0.0.1:{port}/readyz\"]\n\
             \x20     interval: 3s\n\
             \x20     timeout: 3s\n\
             \x20     retries: 40\n",
            config_mount = quote(&format!(
                "{}:/etc/frood/frood.yaml:ro",
                config_path.display()
            )),
        ));
    }

    let mut volumes = vec!["pgdata".to_owned()];
    for (name, module) in crate::modules::containers(loaded) {
        let source = match (&module.build, &module.image) {
            (Some(build), _) => {
                let path = loaded.base_dir.join(build);
                let path = host_path(&path);
                format!("    build: {}\n", quote(&path.display().to_string()))
            }
            (None, Some(image)) => format!("    image: {}\n", quote(image)),
            (None, None) => continue,
        };
        let env = crate::modules::env_file(deploy_dir, name);
        out.push_str(&format!(
            "  {service}:\n\
             {source}\
             \x20   restart: unless-stopped\n\
             \x20   env_file:\n\
             \x20     - {env}\n",
            service = frood_modhost::service_name(name),
            env = quote(&env.display().to_string()),
        ));
        let mut mounts = Vec::new();
        if module.host_docker {
            // The host's Docker (root on the host, A2), a volume for the module's state, and
            // the deployment's network for the containers it starts.
            let data = format!("{}-data", frood_modhost::service_name(name));
            out.push_str(&format!(
                "    environment:\n      FROOD_DOCKER_NETWORK: {network}\n      FROOD_DATA: /data\n",
                network = quote(&format!("{}_default", project_name(loaded))),
            ));
            mounts.push("/var/run/docker.sock:/var/run/docker.sock".to_owned());
            mounts.push(format!("{data}:/data"));
            volumes.push(data);
        }
        // Host folders the config gives the module, e.g. a backup disk.
        for volume in &module.volumes {
            if let Some((host, inside)) = volume.split_once(':') {
                let path = loaded.base_dir.join(host);
                let path = host_path(&path);
                mounts.push(format!("{}:{inside}", path.display()));
            }
        }
        if !mounts.is_empty() {
            out.push_str("    volumes:\n");
            for mount in mounts {
                out.push_str(&format!("      - {}\n", quote(&mount)));
            }
        }
        if deploy.server == ServerPlacement::Host {
            out.push_str(&format!(
                "    ports:\n      - \"127.0.0.1:{}:{}\"\n    extra_hosts:\n      - \"host.docker.internal:host-gateway\"\n",
                frood_modhost::host_port(&loaded.config, name),
                frood_modhost::MODULE_PORT,
            ));
        }
    }

    if loaded.config.server.public_url.is_some() {
        // Only Caddy faces the internet: the server, the database and the modules stay inside
        // (or on 127.0.0.1).
        let https = public_port(loaded);
        let extra = match deploy.server {
            ServerPlacement::Container => String::new(),
            ServerPlacement::Host => {
                "    extra_hosts:\n      - \"host.docker.internal:host-gateway\"\n".to_owned()
            }
        };
        let mut mounts = vec![
            "caddy-data:/data".to_owned(),
            "caddy-config:/config".to_owned(),
            format!("{}:/etc/caddy:ro", deploy_dir.join("caddy").display()),
        ];
        if let Some(routes) = proxy_routes(loaded)
            && let Some(dir) = routes.parent()
        {
            mounts.push(format!("{0}:{0}:ro", dir.display()));
        }
        out.push_str(&format!(
            "  caddy:\n\
             \x20   image: {image}\n\
             \x20   restart: unless-stopped\n\
             \x20   command: [\"caddy\", \"run\", \"--config\", \"{CADDYFILE}\", \"--adapter\", \"caddyfile\"]\n\
             \x20   ports:\n\
             \x20     - \"80:80\"\n\
             \x20     - \"{https}:{https}\"\n\
             \x20   volumes:\n\
             {mounts}\
             {extra}",
            image = quote(CADDY_IMAGE),
            mounts = mounts
                .iter()
                .map(|m| format!("      - {}\n", quote(m)))
                .collect::<String>(),
        ));
        if deploy.server == ServerPlacement::Container {
            out.push_str("    depends_on:\n      - frood\n");
        }
        volumes.push("caddy-data".to_owned());
        volumes.push("caddy-config".to_owned());
    }

    out.push_str("volumes:\n");
    for volume in volumes {
        out.push_str(&format!("  {volume}:\n"));
    }
    out
}

/// Where the Caddyfile is inside the Caddy container; `frood apply` writes it to
/// `.frood/deploy/caddy/Caddyfile`.
pub const CADDYFILE: &str = "/etc/caddy/Caddyfile";

fn public_port(loaded: &Loaded) -> u16 {
    public_url(loaded).and_then(|u| u.port()).unwrap_or(443)
}

fn public_url(loaded: &Loaded) -> Option<url::Url> {
    loaded
        .config
        .server
        .public_url
        .as_deref()
        .and_then(|u| url::Url::parse(u).ok())
}

/// `deploy.proxy.routes` as an absolute path on this machine.
pub fn proxy_routes(loaded: &Loaded) -> Option<std::path::PathBuf> {
    let routes = loaded.config.deploy.proxy.as_ref()?.routes.as_ref()?;
    Some(host_path(&loaded.base_dir.join(routes)))
}

/// The Caddyfile of the HTTPS front, for `server.public_url`. With a path such as `/frood`,
/// Frood answers under it (the path stripped) and at the root only for OAuth discovery
/// (RFC 8414, RFC 9728); the rest of the site is free for `deploy.proxy.routes`.
pub fn caddyfile(loaded: &Loaded) -> Option<String> {
    let public = public_url(loaded)?;
    let host = public.host_str().unwrap_or("localhost");
    let site = match public.port() {
        None | Some(443) => host.to_owned(),
        Some(port) => format!("{host}:{port}"),
    };
    let port = listen_port(loaded);
    let upstream = match loaded.config.deploy.server {
        ServerPlacement::Container => format!("frood:{port}"),
        ServerPlacement::Host => format!("host.docker.internal:{port}"),
    };
    let mut out =
        format!("# Generated by `frood apply`. Do not edit: changes are overwritten.\n{site} {{\n");
    if let Some(routes) = proxy_routes(loaded) {
        out.push_str(&format!(
            "\t# deploy.proxy.routes\n\timport {}\n\n",
            routes.display()
        ));
    }
    let base = public.path().trim_end_matches('/');
    if base.is_empty() {
        out.push_str(&format!(
            "\thandle {{\n\t\treverse_proxy {upstream}\n\t}}\n"
        ));
    } else {
        out.push_str(&format!(
            "\tredir {base} {base}/ 308\n\
             \thandle_path {base}/* {{\n\t\treverse_proxy {upstream}\n\t}}\n\
             \t@frood_discovery path /.well-known/oauth-authorization-server /.well-known/oauth-authorization-server{base} /.well-known/oauth-protected-resource{base}/*\n\
             \thandle @frood_discovery {{\n\t\treverse_proxy {upstream}\n\t}}\n\
             \t# Anything no route claims: a clear answer for clients of an old address.\n\
             \thandle {{\n\t\trespond 404\n\t}}\n"
        ));
    }
    out.push_str("}\n");
    Some(out)
}

/// A host path as Compose needs it: absolute, or Compose takes it for a volume name.
fn host_path(path: &Path) -> std::path::PathBuf {
    path.canonicalize()
        .or_else(|_| std::path::absolute(path))
        .unwrap_or_else(|_| path.to_owned())
}

/// YAML double-quoted scalar; JSON string syntax is valid YAML.
fn quote(value: &str) -> String {
    serde_json::to_string(value).expect("strings serialize")
}

#[cfg(test)]
mod tests {
    use frood_config::{Secrets, TemplateOptions};

    use super::*;

    fn loaded(server: ServerPlacement) -> Loaded {
        let text = frood_config::template(&TemplateOptions {
            name: "personal",
            server,
            build: None,
            image: "ghcr.io/froodai/frood:0.0.1",
            postgres_port: 55432,
        });
        frood_config::parse(&text, &Secrets::from_pairs([("POSTGRES_PASSWORD", "pw")])).unwrap()
    }

    #[test]
    fn host_mode_runs_only_postgres_bound_to_localhost() {
        let out = render(
            &loaded(ServerPlacement::Host),
            Path::new("/x/frood.yaml"),
            Path::new("/x/.frood/secrets.env"),
            Path::new("/x/.frood/deploy"),
        );
        assert!(out.contains("name: frood-personal"));
        assert!(out.contains("\"127.0.0.1:55432:5432\""));
        assert!(out.contains("\"/x/.frood/secrets.env\""));
        assert!(!out.contains("  frood:\n"));
        assert!(
            !out.contains("pw"),
            "secret values never appear in the compose file"
        );
    }

    #[test]
    fn modules_get_services_with_their_own_env_files() {
        let mut loaded = loaded(ServerPlacement::Container);
        loaded.config.modules.insert(
            "stt".into(),
            frood_config::Module {
                image: Some("ghcr.io/froodai/stt-openai:0.0.1".into()),
                build: None,
                url: None,
                port: None,
                secrets: vec!["OPENAI_API_KEY".into()],
                config: Default::default(),
                host_docker: false,
                volumes: vec!["/Volumes/Backup/frood:/repos/disk".into()],
            },
        );
        loaded.config.modules.insert(
            "agents".into(),
            frood_config::Module {
                image: Some("ghcr.io/froodai/runtime-docker:0.0.1".into()),
                build: None,
                url: None,
                port: None,
                secrets: Vec::new(),
                config: Default::default(),
                host_docker: true,
                volumes: Vec::new(),
            },
        );
        let out = render(
            &loaded,
            Path::new("/x/frood.yaml"),
            Path::new("/x/.frood/secrets.env"),
            Path::new("/x/.frood/deploy"),
        );
        assert!(out.contains("  module-stt:\n    image: \"ghcr.io/froodai/stt-openai:0.0.1\""));
        assert!(out.contains("\"/x/.frood/deploy/module-stt.env\""));
        let stt = out.split("  module-stt:").nth(1).unwrap();
        assert!(
            !stt.contains("secrets.env"),
            "a module never gets the whole secrets file"
        );
        assert!(
            !stt.contains("docker.sock"),
            "only modules given host_docker"
        );
        let agents = out
            .split("  module-agents:")
            .nth(1)
            .unwrap()
            .split("  module-stt:")
            .next()
            .unwrap();
        assert!(agents.contains("/var/run/docker.sock:/var/run/docker.sock"));
        assert!(stt.contains("\"/Volumes/Backup/frood:/repos/disk\""));
        assert!(agents.contains("FROOD_DOCKER_NETWORK: \"frood-personal_default\""));
        assert!(out.ends_with("volumes:\n  pgdata:\n  module-agents-data:\n"));
        let parsed: serde_yaml_ng::Value = serde_yaml_ng::from_str(&out).unwrap();
        assert!(parsed["services"]["module-agents"]["volumes"].is_sequence());
    }

    #[test]
    fn container_mode_adds_server_with_health_check() {
        let out = render(
            &loaded(ServerPlacement::Container),
            Path::new("/x/frood.yaml"),
            Path::new("/x/.frood/secrets.env"),
            Path::new("/x/.frood/deploy"),
        );
        assert!(out.contains("  frood:\n    image: \"ghcr.io/froodai/frood:0.0.1\""));
        assert!(out.contains("\"127.0.0.1:8080:8080\""));
        assert!(out.contains("FROOD_DB_HOST: postgres"));
        assert!(out.contains("\"/x/frood.yaml:/etc/frood/frood.yaml:ro\""));
        // Secrets reach the server through its environment only: the file is not mounted, so
        // its owner and permissions on the host do not matter.
        assert!(!out.contains("secrets.env:/etc/frood"));
        assert!(out.contains("condition: service_healthy"));
    }

    #[test]
    fn a_public_address_puts_caddy_in_front() {
        let mut container = loaded(ServerPlacement::Container);
        container.config.server.public_url = Some("https://1-2-3-4.sslip.io".into());
        let out = render(
            &container,
            Path::new("/x/frood.yaml"),
            Path::new("/x/.frood/secrets.env"),
            Path::new("/x/.frood/deploy"),
        );
        let parsed: serde_json::Value = serde_yaml_ng::from_str(&out).unwrap();
        let caddy = &parsed["services"]["caddy"];
        assert_eq!(caddy["command"][3], CADDYFILE);
        assert_eq!(caddy["ports"], serde_json::json!(["80:80", "443:443"]));
        assert_eq!(caddy["volumes"][2], "/x/.frood/deploy/caddy:/etc/caddy:ro");
        let file = caddyfile(&container).unwrap();
        assert!(file.contains("1-2-3-4.sslip.io {\n\thandle {\n\t\treverse_proxy frood:8080\n"));
        assert!(parsed["volumes"].get("caddy-data").is_some());
        // Nothing else listens beyond this machine.
        for (name, service) in parsed["services"].as_object().unwrap() {
            if name == "caddy" {
                continue;
            }
            for port in service["ports"].as_array().into_iter().flatten() {
                assert!(
                    port.as_str().unwrap().starts_with("127.0.0.1:"),
                    "{name}: {port}"
                );
            }
        }
        let mut host = loaded(ServerPlacement::Host);
        host.config.server.public_url = Some("https://mem.example.com:8443".into());
        let out = render(
            &host,
            Path::new("/x/frood.yaml"),
            Path::new("/x/.frood/secrets.env"),
            Path::new("/x/.frood/deploy"),
        );
        let parsed: serde_json::Value = serde_yaml_ng::from_str(&out).unwrap();
        let caddy = &parsed["services"]["caddy"];
        assert_eq!(caddy["ports"][1], "8443:8443");
        let file = caddyfile(&host).unwrap();
        assert!(file.contains("mem.example.com:8443 {"));
        assert!(file.contains("reverse_proxy host.docker.internal:8080"));
        assert!(
            render(
                &loaded(ServerPlacement::Container),
                Path::new("/x/frood.yaml"),
                Path::new("/x/s"),
                Path::new("/x/d")
            )
            .find("caddy")
            .is_none()
        );
    }

    #[test]
    fn under_a_path_frood_leaves_the_rest_of_the_site_to_other_routes() {
        let dir = tempfile::tempdir().unwrap();
        std::fs::write(dir.path().join("pages.caddy"), "handle /pages/* {\n}\n").unwrap();
        let mut loaded = loaded(ServerPlacement::Container);
        loaded.base_dir = dir.path().to_owned();
        loaded.config.server.public_url = Some("https://1-2-3-4.sslip.io/frood/".into());
        loaded.config.deploy.proxy = Some(frood_config::Proxy {
            routes: Some("pages.caddy".into()),
        });
        let caddyfile = caddyfile(&loaded).unwrap();
        let routes = dir.path().canonicalize().unwrap();
        assert!(caddyfile.contains(&format!("\timport {}/pages.caddy\n", routes.display())));
        assert!(caddyfile.contains("\thandle_path /frood/* {\n\t\treverse_proxy frood:8080\n"));
        assert!(caddyfile.contains("redir /frood /frood/ 308"));
        assert!(caddyfile.contains(
            "path /.well-known/oauth-authorization-server /.well-known/oauth-authorization-server/frood /.well-known/oauth-protected-resource/frood/*"
        ));
        assert!(
            caddyfile.contains("\thandle {\n\t\trespond 404\n"),
            "the root is not Frood's"
        );
        let out = render(
            &loaded,
            Path::new("/x/frood.yaml"),
            Path::new("/x/.frood/secrets.env"),
            Path::new("/x/.frood/deploy"),
        );
        let parsed: serde_json::Value = serde_yaml_ng::from_str(&out).unwrap();
        assert_eq!(
            parsed["services"]["caddy"]["volumes"][3],
            format!("{0}:{0}:ro", routes.display())
        );
    }

    #[test]
    fn rendered_file_is_valid_yaml() {
        for server in [ServerPlacement::Host, ServerPlacement::Container] {
            let out = render(
                &loaded(server),
                Path::new("/x/frood.yaml"),
                Path::new("/x/.frood/secrets.env"),
                Path::new("/x/.frood/deploy"),
            );
            let parsed: serde_json::Value = serde_yaml_ng::from_str(&out).unwrap();
            assert!(parsed["services"]["postgres"].is_object());
            assert!(parsed["volumes"].get("pgdata").is_some());
        }
    }
}
