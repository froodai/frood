//! The module's words in the eight languages of Frood's interface (docs/25 §3.4), the same as
//! the Telegram bot's. The language comes from the module's config (`language`).

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub(crate) enum Lang {
    En,
    Zh,
    Es,
    Hi,
    Ar,
    Fr,
    Pt,
    Ru,
}

impl Lang {
    /// From the config's code; English for anything else.
    pub(crate) fn from_code(code: &str) -> Self {
        match code {
            "zh" => Self::Zh,
            "es" => Self::Es,
            "hi" => Self::Hi,
            "ar" => Self::Ar,
            "fr" => Self::Fr,
            "pt" => Self::Pt,
            "ru" => Self::Ru,
            _ => Self::En,
        }
    }

    pub(crate) fn words(self) -> &'static Words {
        match self {
            Self::En => &EN,
            Self::Zh => &ZH,
            Self::Es => &ES,
            Self::Hi => &HI,
            Self::Ar => &AR,
            Self::Fr => &FR,
            Self::Pt => &PT,
            Self::Ru => &RU,
        }
    }
}

