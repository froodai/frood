//! The bot's words in the eight languages of Frood's interface (docs/25 §3.4). The language
//! comes from the module's config (`language`); the menu is set in every language, so Telegram
//! shows each person the commands in theirs.

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub(crate) enum Lang {
    En,
    Zh,
    Es,
    Hi,
    Ar,
    Fr,
    Pt,
    Ru,
}

impl Lang {
    pub(crate) const ALL: [Lang; 8] = [
        Lang::En,
        Lang::Zh,
        Lang::Es,
        Lang::Hi,
        Lang::Ar,
        Lang::Fr,
        Lang::Pt,
        Lang::Ru,
    ];

    /// From the config's code; English for anything else.
    pub(crate) fn from_code(code: &str) -> Self {
        Self::ALL
            .into_iter()
            .find(|l| l.code() == code)
            .unwrap_or(Lang::En)
    }

    pub(crate) fn code(self) -> &'static str {
        match self {
            Self::En => "en",
            Self::Zh => "zh",
            Self::Es => "es",
            Self::Hi => "hi",
            Self::Ar => "ar",
            Self::Fr => "fr",
            Self::Pt => "pt",
            Self::Ru => "ru",
        }
    }

    pub(crate) fn texts(self) -> &'static Texts {
        match self {
            Self::En => &EN_TEXTS,
            Self::Zh => &ZH_TEXTS,
            Self::Es => &ES_TEXTS,
            Self::Hi => &HI_TEXTS,
            Self::Ar => &AR_TEXTS,
            Self::Fr => &FR_TEXTS,
            Self::Pt => &PT_TEXTS,
            Self::Ru => &RU_TEXTS,
        }
    }

    pub(crate) fn words(self) -> &'static Words {
        match self {
            Self::En => &EN_WORDS,
            Self::Zh => &ZH_WORDS,
            Self::Es => &ES_WORDS,
            Self::Hi => &HI_WORDS,
            Self::Ar => &AR_WORDS,
            Self::Fr => &FR_WORDS,
            Self::Pt => &PT_WORDS,
            Self::Ru => &RU_WORDS,
        }
    }
}

