#[cfg(test)]
mod tests {
    use super::*;

    /// Placeholders a translation must keep, per message.
    fn holes(text: &str) -> Vec<&str> {
        let mut out: Vec<&str> = text
            .match_indices('{')
            .filter_map(|(i, _)| text[i + 1..].split_once('}').map(|(name, _)| name))
            .collect();
        out.sort_unstable();
        out
    }

    #[test]
    fn every_language_keeps_the_placeholders_of_english() {
        let en = Lang::En;
        for lang in Lang::ALL {
            let (t, e) = (lang.texts(), en.texts());
            for (a, b) in [
                (t.waiting_n, e.waiting_n),
                (t.changed_n, e.changed_n),
                (t.since, e.since),
                (t.inbox_more, e.inbox_more),
                (t.date, e.date),
                (t.taken_back_kept, e.taken_back_kept),
                (t.accept_all, e.accept_all),
                (t.accepted_all, e.accepted_all),
            ] {
                assert_eq!(holes(a), holes(b), "{lang:?}: {a}");
            }
            let (w, e) = (lang.words(), en.words());
            for (a, b) in [
                (w.due_in, e.due_in),
                (w.due_ago, e.due_ago),
                (w.more, e.more),
                (w.module_down, e.module_down),
                (w.failing, e.failing),
                (w.queued_long, e.queued_long),
                (w.overrun, e.overrun),
                (w.source_stale, e.source_stale),
                (w.budget, e.budget),
            ] {
                assert_eq!(holes(a), holes(b), "{lang:?}: {a}");
            }
            assert_eq!(Lang::from_code(lang.code()), lang);
        }
        assert_eq!(Lang::from_code("klingon"), Lang::En);
    }
}
